export function getCropBenchmark(cropQuery: string): CropBenchmark {
  const clean = cropQuery.toLowerCase().trim();
  for (const [key, benchmark] of Object.entries(CROP_PRICE_BENCHMARKS)) {
    if (
      clean.includes(key) ||
      key.includes(clean) ||
      benchmark.crop.toLowerCase().includes(clean) ||
      Object.values(benchmark.cropLocalName).some((n) => n.toLowerCase().includes(clean))
    ) {
      return benchmark;
    }
  }

  // Generic fallback benchmark
  return {
    crop: cropQuery || "Agricultural Produce",
    category: "Vegetables",
    minPrice: 3200,
    maxPrice: 4500,
    modalPrice: 3900,
    unit: "Quintal (100 kg)",
    cropLocalName: {
      en: cropQuery || "Produce",
      hi: cropQuery || "फसल",
      kn: cropQuery || "ಬೆಳೆ",
      te: cropQuery || "పంట",
      ta: cropQuery || "பயிர்",
      mr: cropQuery || "पीक",
      pa: cropQuery || "ਫਸਲ",
      bn: cropQuery || "ফসল",
      gu: cropQuery || "પાક",
    },
  };
}

export function generateDynamicMandiRates(
  cropQuery: string,
  stateName: string,
  districtName?: string
): MandiPriceItem[] {
  const benchmark = getCropBenchmark(cropQuery);
  const effectiveState = stateName && stateName !== "All States" ? stateName : "Karnataka";
  const stateDistricts = INDIAN_STATES_AND_DISTRICTS[effectiveState] || ["Bangalore", "Mysuru", "Tumakuru", "Mandya", "Hassan"];

  let targetDistricts: string[] = [];
  if (districtName && districtName !== "All Districts") {
    targetDistricts = [districtName];
    // Add 2-3 other districts from same state to give comparison
    const otherDistricts = stateDistricts.filter((d) => d.toLowerCase() !== districtName.toLowerCase());
    targetDistricts = [districtName, ...otherDistricts.slice(0, 3)];
  } else {
    targetDistricts = stateDistricts.slice(0, 6);
  }

  return targetDistricts.map((dist, idx) => {
    // Slight realistic variation across districts (+- 4-8%)
    const priceVariance = (idx === 0 ? 0 : idx % 2 === 0 ? 0.04 : -0.03) + (idx * 0.01);
    const modal = Math.round(benchmark.modalPrice * (1 + priceVariance));
    const min = Math.round(modal * 0.88);
    const max = Math.round(modal * 1.14);
    const trend = idx % 3 === 0 ? "up" : idx % 3 === 1 ? "down" : "stable";
    const change = Number(((idx % 2 === 0 ? 1 : -1) * (1.2 + (idx * 0.7))).toFixed(1));

    return {
      id: `dyn_mnd_${dist.replace(/\s+/g, "_")}_${Date.now()}_${idx}`,
      crop: benchmark.crop,
      cropLocalName: benchmark.cropLocalName,
      category: benchmark.category,
      market: `${dist} APMC Main Market Yard`,
      district: dist,
      state: effectiveState,
      minPrice: min,
      maxPrice: max,
      modalPrice: modal,
      unit: benchmark.unit,
      changePercent: change,
      trend: trend,
      lastUpdated: "Live Trading (Today, 10:30 AM)",
      historicalPrices: [
        { day: "Mon", price: Math.round(modal * 0.96) },
        { day: "Tue", price: Math.round(modal * 0.98) },
        { day: "Wed", price: Math.round(modal * 0.97) },
        { day: "Thu", price: Math.round(modal * 0.99) },
        { day: "Fri", price: Math.round(modal * 0.995) },
        { day: "Sat", price: modal },
      ],
    };
  });
}

